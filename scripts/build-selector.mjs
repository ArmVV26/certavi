// Builds docs/design/selector.html: a self-contained page (no network, works from file://) to
// compare the candidate palettes and font pairings for Certavi.
//
// The fonts are read from node_modules/@fontsource* (Latin subset, woff2) and embedded as base64,
// so the page needs nothing else. Fonts loaded by relative URL would be blocked on file://.
//
// Usage: node scripts/build-selector.mjs

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const templatePath = path.join(root, 'scripts', 'selector', 'template.html');
const outputPath = path.join(root, 'docs', 'design', 'selector.html');
const MARKER = '/* @FONT_FACES@ */';

/** @type {{ family: string; file: string; weight: string }[]} */
const FACES = [
  {
    family: 'Inter Variable',
    file: '@fontsource-variable/inter/files/inter-latin-wght-normal.woff2',
    weight: '100 900',
  },
  {
    family: 'Manrope Variable',
    file: '@fontsource-variable/manrope/files/manrope-latin-wght-normal.woff2',
    weight: '200 800',
  },
  {
    family: 'JetBrains Mono Variable',
    file: '@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2',
    weight: '100 800',
  },
  {
    family: 'Archivo Variable',
    file: '@fontsource-variable/archivo/files/archivo-latin-wght-normal.woff2',
    weight: '100 900',
  },
  ...[400, 500, 600, 700].map((w) => ({
    family: 'Barlow',
    file: `@fontsource/barlow/files/barlow-latin-${String(w)}-normal.woff2`,
    weight: String(w),
  })),
  ...[400, 500, 600, 700].map((w) => ({
    family: 'Barlow Condensed',
    file: `@fontsource/barlow-condensed/files/barlow-condensed-latin-${String(w)}-normal.woff2`,
    weight: String(w),
  })),
];

const missing = FACES.filter((f) => !existsSync(path.join(root, 'node_modules', f.file)));
if (missing.length > 0) {
  console.error('Missing font files (install the @fontsource packages first):');
  for (const f of missing) console.error(`  - ${f.file}`);
  process.exit(1);
}

const fontFaces = FACES.map((f) => {
  const data = readFileSync(path.join(root, 'node_modules', f.file)).toString('base64');
  return (
    `@font-face{font-family:'${f.family}';font-style:normal;font-display:swap;` +
    `font-weight:${f.weight};src:url(data:font/woff2;base64,${data}) format('woff2');}`
  );
}).join('\n');

const template = readFileSync(templatePath, 'utf8');
if (!template.includes(MARKER)) {
  console.error(`Template ${templatePath} has no ${MARKER} marker.`);
  process.exit(1);
}

const banner =
  '<!-- Generated by scripts/build-selector.mjs from scripts/selector/template.html. Do not edit. -->\n';
// Swap the template's own header comment for the "generated" banner.
const html = template
  .replace(/<!--\s*Template for[\s\S]*?-->\n/, banner)
  .replace(MARKER, fontFaces);
writeFileSync(outputPath, html);

const kb = Math.round(Buffer.byteLength(html) / 1024);
console.log(
  `Wrote ${path.relative(root, outputPath)} (${String(kb)} KB, ${String(FACES.length)} font files).`,
);
